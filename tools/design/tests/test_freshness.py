    assert run_check(dvc_repo, capsys) == (1, f'tools/stages.yaml at {dvc_repo}: stages.yaml needs "dvc: <version>" '
                                              'and a "stages:" map\n' + RUN + '\n')
    write(dvc_repo, STAGES_PATH, 'dvc: 3.67.1\nstages:\n')
    assert run_check(dvc_repo, capsys)[0] == 1


