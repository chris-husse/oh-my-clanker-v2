def test_recorded_at_ignores_a_no_ff_merge(dvc_repo, capsys):
    marked(dvc_repo, ['page'], capsys)
    commit(dvc_repo, 'page marked', 'dvc.lock')
    git(dvc_repo, 'checkout', '-q', '-b', 'side')
    write(dvc_repo, 'notes/s.md', 's2')
    marked(dvc_repo, ['page'], capsys)
    side = commit(dvc_repo, 'page re-marked on side', 'dvc.lock', 'notes/s.md')
    git(dvc_repo, 'checkout', '-q', 'main')
    write(dvc_repo, 'parts/row.md', 'row2')
    marked(dvc_repo, ['item--a.one'], capsys)
    commit(dvc_repo, 'main: something else', 'dvc.lock', 'parts/row.md')
    git(dvc_repo, 'merge', '-q', '--no-ff', '-m', 'merge side', 'side')
    assert len(git(dvc_repo, 'rev-list', '--parents', '-n1', 'HEAD').split()) == 3
    assert recorded_at(dvc_repo, 'page') == side


def test_recorded_at_is_null_when_heads_lock_lacks_the_stage(dvc_repo, capsys, monkeypatch):
    marked(dvc_repo, ['page', 'item--a.one'], capsys)
    commit(dvc_repo, 'marked', 'dvc.lock')
    write(dvc_repo, STAGES_PATH, STAGES[:STAGES.index('  page:')])
    generate(dvc_repo)
    lock = dvc_repo / 'dvc.lock'
    data = yaml.safe_load(lock.read_text())
    del data['stages']['page']
    lock.write_text(yaml.safe_dump(data, sort_keys=False))
    commit(dvc_repo, 'page removed')
    assert recorded_at(dvc_repo, 'page') is None
    assert recorded_at(dvc_repo, 'item--a.one') is not None
    monkeypatch.chdir(dvc_repo)
    capsys.readouterr()
    assert recorded_at_main(['page']) == 1 and capsys.readouterr().out == ''
    assert recorded_at_main([]) == 1
    assert recorded_at_main(['item--a.one']) == 0
    assert capsys.readouterr().out == recorded_at(dvc_repo, 'item--a.one') + '\n'


