def marked(root, names, capsys):
    code = mark(root, names)
    out = capsys.readouterr()
    assert code == 0, out
    return out.out


def commit(root, message, *paths):
    git(root, 'add', *(paths or ['-A']))
    git(root, 'commit', '-q', '-m', message)
    return git(root, 'rev-parse', 'HEAD').strip()


