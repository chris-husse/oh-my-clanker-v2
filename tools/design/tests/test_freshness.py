# --- the pure part: declaration, expansion, rendering -------------------------------------------------------------

DECL = '''\
dvc: 3.67.1
stages:
  outline:
    skill: /write-outline
    inputs: [notes/**/*.md, parts/*.md]
    outputs: [defs/*.md]
    exclude: [defs/README.md]
  item:
    skill: /build-items
    each: defs/*.md
    root: defs
    exclude: [defs/README.md]
    inputs: ['{each}', parts/blocks/*.md]
    outputs: ['lib/{group}/{name}.txt']
  page-es:
    skill: /translate es
    each: pages/en/**/*.md
    root: pages/en
    inputs: ['{each}']
    outputs: ['pages/es/{id}.md']
'''

FILES = sorted([
    'notes/main.md',
    'notes/sub/extra.md',
    'parts/FORMAT.md',
    'defs/README.md',
    'defs/alpha.first.md',
    'defs/beta.second.md',
    'parts/blocks/row.md',
    'lib/alpha/first.txt',
    'lib/beta/second.txt',
    'pages/en/README.md',
    'pages/en/1-intro/README.md',
    'pages/en/1-intro/1.1-start.md',
    'pages/es/README.md',
])


def parse(text: str, tmp_path) -> Declaration:
    (tmp_path / 'tools').mkdir(exist_ok=True)
    (tmp_path / STAGES_PATH).write_text(text)
    return declaration_at(tmp_path)


def test_the_declaration_parses_keeping_version_order_and_each(tmp_path):
    d = parse(DECL, tmp_path)
    assert d.dvc == '3.67.1'
    assert [s.name for s in d.stages] == ['outline', 'item', 'page-es']
    assert d.stages[1].each == 'defs/*.md' and d.stages[1].root == 'defs'
    assert d.stages[0].exclude == ['defs/README.md'] and d.stages[0].each is None


def test_globs_expand_sorted_recursive_literal_and_empty():
    def deps(glob):
        return expand_all(Declaration('3.67.1', [StageDecl('x', '/s', [glob], [], None, None, [])]), FILES)[0].deps

    assert deps('notes/**/*.md') == ['notes/main.md', 'notes/sub/extra.md']
    assert deps('parts/*.md') == ['parts/FORMAT.md']
    assert deps('defs/alpha.first.md') == ['defs/alpha.first.md']
    assert deps('none/*.md') == []


def test_an_all_to_all_stage_is_one_dvc_stage_without_its_excludes(tmp_path):
    s = next(s for s in expand_all(parse(DECL, tmp_path), FILES) if s.name == 'outline')
    assert s.deps == ['notes/main.md', 'notes/sub/extra.md', 'parts/FORMAT.md']
    assert s.outs == ['defs/alpha.first.md', 'defs/beta.second.md']
    assert s.cmd == '/write-outline' and s.decl == 'outline'


def test_a_one_to_one_stage_is_one_dvc_stage_per_item_with_group_and_name(tmp_path):
    items = [s for s in expand_all(parse(DECL, tmp_path), FILES) if s.decl == 'item']
    assert [s.name for s in items] == ['item--alpha.first', 'item--beta.second']
    assert items[0].deps == ['defs/alpha.first.md', 'parts/blocks/row.md']
    assert items[0].outs == ['lib/alpha/first.txt']


def test_a_not_yet_built_one_to_one_output_is_declared(tmp_path):
    items = [s for s in expand_all(parse(DECL, tmp_path), FILES) if s.decl == 'page-es']
    assert [s.name for s in items] == ['page-es--1-intro/1.1-start', 'page-es--1-intro/README', 'page-es--README']
    assert items[0].outs == ['pages/es/1-intro/1.1-start.md']


def test_stage_decl_of_takes_the_part_before_the_double_dash():
    assert stage_decl_of('item--alpha.first') == 'item'
    assert stage_decl_of('page-es--1-intro/README') == 'page-es'
    assert stage_decl_of('outline') == 'outline'


def test_the_rendering_is_byte_stable_with_header_quoting_and_cache_false(tmp_path):
    d = parse(DECL, tmp_path)
    a = render_dvc_yaml(expand_all(d, FILES))
    b = render_dvc_yaml(list(reversed(expand_all(d, list(reversed(FILES))))))
    assert a == b
    assert a.startswith('# Generated by `just ensure-up-to-date` from tools/stages.yaml. Do not edit.\nstages:\n')
    assert "  'item--alpha.first':\n    cmd: '/build-items'\n    deps:\n" in a
    assert "    - 'lib/alpha/first.txt':\n        cache: false\n" in a


def test_a_single_quote_is_doubled():
    y = render_dvc_yaml([DvcStage('x', 'x', '/s', ["a'b.md"], [])])
    assert "    - 'a''b.md'\n" in y
    assert 'outs:' not in y


def test_zero_stages_render_an_empty_map(tmp_path):
    d = parse('dvc: 3.67.1\nstages: {}\n', tmp_path)
    assert d.stages == []
    assert render_dvc_yaml(expand_all(d, FILES)).endswith('\nstages: {}\n')


def test_an_id_with_a_double_dash_is_refused(tmp_path):
    with pytest.raises(FormatError, match='item id "a--b" of stage item contains --'):
        expand_all(parse(DECL, tmp_path), ['defs/a--b.md'])


def test_a_stage_without_inputs_is_refused(tmp_path):
    with pytest.raises(FormatError, match='stage x needs a skill and inputs'):
        parse('dvc: 3.67.1\nstages:\n  x:\n    skill: /s\n    inputs: []\n    outputs: []\n', tmp_path)


