def write(root, rel, text):
    p = root / rel
    p.parent.mkdir(parents=True, exist_ok=True)
    p.write_text(text)


def generate(root):
    """dvc.yaml as mark writes it, without recording anything."""
    assert mark(root, ['--generate-only']) == 0


